#include <iostream>
#include <math.h>
using namespace std;
int main() {

    double angle = 0;

    cout << "sin(0) = "
         << sin(angle)
         << endl;

    cout << "cos(0) = "
         << cos(angle)
         << endl;

    cout << "tan(0) = "
         << tan(angle)
         << endl;

    return 0;
}