#include <iostream>
#include <cmath> 
using namespace std; 
int main() {     
     double num = 144;     
     double result = sqrt(num);     
     double power = pow(2, 10);     
     cout << "Square root of 144 = " << result << endl;     
     cout << "2 ^ 10 = " << power << endl;     
     return 0;
} 